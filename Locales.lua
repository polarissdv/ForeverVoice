ns.LANGUAGES = { "fr", "en" }

function ns.DefaultLanguage()
    return GetLocale() == "frFR" and "fr" or "en"
end

local function Language()
    local lang = ns.db and ns.db.language
    if not L[lang] then lang = ns.DefaultLanguage() end
    return lang
end

ns.L = setmetatable({}, {
    __index = function(_, key)
        return L[Language()][key] or L.en[key] or key
    end,
})
